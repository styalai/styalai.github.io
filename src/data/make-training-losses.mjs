// ---------------------------------------------------------------------------
// Regenerates src/data/training-losses.json
//
//   npm run data
//
// WHY THIS EXISTS: the sample post ships with *synthetic* curves rather than
// measurements from a real training run. Keeping the generator next to the
// data means that claim is checkable -- you can read exactly how the numbers
// were produced instead of trusting them.
//
// To use real data instead: replace training-losses.json with your own export
// and keep the same shape (see `src/lib/types.ts` for the schema). Nothing in
// the charts cares where the numbers came from.
// ---------------------------------------------------------------------------
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));

/**
 * Deterministic pseudo-random numbers (mulberry32).
 *
 * Math.random() would give different numbers on every run, so charts would
 * jitter every time you regenerated. A fixed seed keeps the dataset stable.
 */
function makeRandom(seed) {
  let a = seed;
  return function random() {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const STEPS = 60;

/**
 * The three learning rates compared in the post, and the character of each run:
 *
 *  - start:  initial loss (~ln(vocab), which is where these toy runs begin)
 *  - tau:    how quickly the curve bends toward its floor. Bigger = slower.
 *  - floor:  the loss it settles at. A higher floor means a worse run.
 *  - noise:  per-step jitter. Real minibatch losses are never smooth.
 *  - wobble: slow low-frequency drift, so curves look measured, not analytic.
 *  - maxStableJump: the largest step-to-step loss increase tolerated before
 *    the run is called unstable. Derived from the noise amplitude above.
 */
const RUNS = [
  {
    lr: 0.001,
    label: '1e-3',
    colorIndex: 0,
    start: 3.4,
    tau: 26,
    floor: 2.55,
    noise: 0.035,
    wobble: 0.012,
    maxStableJump: 0.06,
  },
  {
    lr: 0.003,
    label: '3e-3',
    colorIndex: 1,
    start: 3.4,
    tau: 13,
    floor: 2.18,
    noise: 0.045,
    wobble: 0.01,
    maxStableJump: 0.08,
  },
  {
    lr: 0.01,
    label: '1e-2',
    colorIndex: 2,
    start: 3.4,
    // A large learning rate buys a fast early drop and then pays for it: the
    // floor is *worse* than the mid-range run, and the tail is visibly jumpy.
    tau: 6,
    floor: 2.46,
    noise: 0.075,
    wobble: 0.045,
    maxStableJump: 0.08,
  },
];

const series = RUNS.map((run, runIndex) => {
  const random = makeRandom(1337 + runIndex * 101);

  const points = [];
  for (let step = 0; step <= STEPS; step += 1) {
    // Exponential approach to the floor: fast at first, then it flattens.
    const progress = 1 - Math.exp(-step / run.tau);
    const base = run.start - (run.start - run.floor) * progress;
    const noise = (random() - 0.5) * 2 * run.noise;
    const wobble = Math.sin(step / 4.5 + runIndex) * run.wobble;
    points.push({
      step,
      // Round to 3 decimals: nobody measures loss to 12 significant figures.
      loss: Number((base + noise + wobble).toFixed(3)),
    });
  }

  return {
    lr: run.lr,
    label: run.label,
    colorIndex: run.colorIndex,
    // Honest label for how wobbly this run was, judged from the curve itself
    // rather than hand-set.
    unstable: maxStepJump(points) > run.maxStableJump,
    points,
  };
});

/** Largest single-step increase in loss. A proxy for instability. */
function maxStepJump(points) {
  let worst = 0;
  for (let i = 1; i < points.length; i += 1) {
    worst = Math.max(worst, points[i].loss - points[i - 1].loss);
  }
  return worst;
}

/**
 * End-of-run and best loss, computed from the generated points so the summary
 * table can never disagree with the curves plotted next to it.
 */
const summary = series.map((s) => {
  const losses = s.points.map((p) => p.loss);
  return {
    lr: s.lr,
    label: s.label,
    colorIndex: s.colorIndex,
    finalLoss: losses.at(-1),
    bestLoss: Math.min(...losses),
    unstable: s.unstable,
  };
});

const data = {
  meta: {
    description:
      'Synthetic data. Curves are generated by src/data/make-training-losses.mjs, not measured from a real training run.',
    steps: STEPS,
    unit: 'cross-entropy loss (nats/token)',
  },
  series,
  summary,
};

const target = join(here, 'training-losses.json');
writeFileSync(target, JSON.stringify(data, null, 2) + '\n');
console.log(`Wrote ${target}`);
console.log(`  ${series.length} curves x ${series.length * (STEPS + 1)} points, ${STEPS} steps`);